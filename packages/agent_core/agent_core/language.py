def normalize_colloquial(message: str) -> str:
    text = unicodedata.normalize("NFKC", str(message or "")).strip()
    text = re.sub(r"\s+", "", text)
    for source, target in COLLOQUIAL_REPLACEMENTS:
        text = text.replace(source, target)
    text = re.sub(r"(?<!\d)(2[2-9])年", r"20\1年", text)
    text = re.sub(r"第?(\d+)个专业", r"\1专业", text)
    text = re.sub(r"土木(?=专业|系|多招|招|录|计划|增加|减少|怎么|会)", "土木工程", text)
    text = re.sub(r"计算机(?=专业|系|多招|招|录|计划|增加|减少|怎么|会)", "计算机科学与技术", text)
    text = re.sub(r"软工(?=专业|系|多招|招|录|计划|增加|减少|怎么|会)", "软件工程", text)
    text = re.sub(r"临床(?=专业|系|多招|招|录|计划|增加|减少|怎么|会)", "临床医学", text)
    text = re.sub(r"多招(\d+)(?:个)?(?:名额|人|计划)?", r"增加\1个计划", text)
    text = re.sub(r"少招(\d+)(?:个)?(?:名额|人|计划)?", r"减少\1个计划", text)
    text = re.sub(r"多少个人", "多少人", text)
    surname_pattern = "|".join(COMMON_SURNAMES)
    text = re.sub(
        rf"({surname_pattern})性(?=(?:学生|考生|同学|的|有多少|人数|人|录取))",
        r"\1姓",
        text,
    )
    text = re.sub(
        rf"性({surname_pattern})(?=(?:学生|考生|同学|的|有多少|人数|人|录取))",
        r"姓\1",
        text,
    )
    for filler in TRAILING_FILLERS:
        text = re.sub(f"{filler}(?=[？?。！!，,]|$)", "", text)
    text = re.sub(r"[？?]{2,}", "？", text)
    return text.strip("，,。；;")


def colloquial_variants(question: str) -> list[str]:
    base = question.strip().rstrip("？?")
    return list(
        dict.fromkeys(
            [
                question.strip(),
                f"麻烦帮我看看，{base}呀？",
                f"想问一下，{base}？",
                f"帮我查查{base}呗？",
                f"咱学校{base}咋样？",
            ]
        )
    )
